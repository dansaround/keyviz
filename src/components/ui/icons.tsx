// Ctrl/Alt legends traced from photos of an ASUS ROG laptop keyboard (potrace), used as icons on Windows.
// Single-color paths drawn with the key's text color; the legend height is ~45% of `size`, width follows the aspect ratio.
function createLegendIcon(name: string, width: number, height: number, d: string) {
    const Icon = forwardRef<SVGSVGElement, LucideProps>(
        ({ color = "currentColor", size = 24, style }, ref) => {
            const h = Number(size) * 0.45;
            return (
                <svg
                    ref={ref}
                    xmlns="http://www.w3.org/2000/svg"
                    height={h}
                    width={(h * width) / height}
                    viewBox={`0 0 ${width} ${height}`}
                    style={style}
                >
                    <g transform={`translate(0,${height}) scale(0.1,-0.1)`} fill={color} stroke="none">
                        <path d={d} />
                    </g>
                </svg>
            );
        }
    );
    Icon.displayName = name;
    return Icon;
}

